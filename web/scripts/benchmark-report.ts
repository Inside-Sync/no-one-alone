/**
 * Benchmark report for the submission (plan item B2): runs the same labelled scenario set as the Benchmark tab and writes
 * `docs/submission/test-report.md`, in English, for judges.
 *
 *   npm run benchmark:report
 *
 * The runner is the TypeScript engine itself, so the script runs under Vitest (it already resolves the `@/` imports and the JSON locales);
 * `scripts/run-benchmark-report.mjs` starts that run. Nothing here needs another dependency.
 */
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import tc from '../src/locales/en/tcBench.json'
import testcase from '../src/locales/en/testcase.json'
import { BENCH_GROUPS, SCENARIOS, computeMetrics, pct, runAllSync, type Metrics, type Outcome, type Rate, type ScenarioResult } from '../src/features/testcase/bench'

/** Found by the first run of this benchmark and fixed in the engine since; the scenarios now match. Listed in section 7 for honesty. */
export const FIXED: readonly string[] = [
  'T-glu-02 and T-glu-40 (safety): an implausible glucose (0.2 or 40 mmol/L) typed for a person with diabetes was not held back, because the "glucose sensor is missing" warning hid the refusal and the run went ahead with the sensor treated as off. An implausible value is now always a required issue that blocks the run, whatever other warnings are open.',
  'C-hf-weight-hypo (labelling): when low sugar (R3) and a weight rise (R4) were met in the same minute the first sensor rule was recorded as R4. It is now recorded by rule priority (R3); the decision (R9) was already right and is unchanged.',
  'C-hypo-fall-cant and C-hypo-spo2 (safety order): low sugar was checked before a fall with "can\'t get up" and before oxygen under 90, so both ended at home treatment (R9). Every 998 line (R6, R7, R5, R8) is now checked before the home lines, so both are now 998. Heart failure with no answer is now R5, as the rule table says; it was already 998.',
  'Prevention result value (no scenario): the result slider value had no plausibility check unlike the other inputs. It is now refused and reported the same way (unit tests in `web/tests/testcase/inputs.test.ts`).',
]

/** What the benchmark found about the engine, by scenario id: written once here, shown next to the difference in the report. */
export const FINDINGS: Record<string, string> = {}

const en = tc as unknown as Record<string, Record<string, unknown>>
const label = (group: string, key: string): string => String((en[group] as Record<string, unknown>)[key] ?? key)
const dec = (o: Outcome): string => `${o.rule === 'none' ? '' : o.rule + ' · '}${label('decision', o.decision)}`
const ci = (r: Rate): string => (r.n ? `${pct(r.p)} (95% CI ${pct(r.lo)} to ${pct(r.hi)}; ${r.k} of ${r.n})` : 'n/a')
const cell = (s: string): string => s.replace(/\|/g, '/').replace(/\n/g, ' ')
const table = (head: string[], rows: string[][]): string =>
  [`| ${head.join(' | ')} |`, `| ${head.map(() => '---').join(' | ')} |`, ...rows.map((r) => `| ${r.map(cell).join(' | ')} |`)].join('\n')

const ruleWhen = (id: string): string => {
  const path = id.startsWith('R') ? ['rules', id] : ['prevention', 'rules', id]
  const o = path.reduce<unknown>((x, k) => (x as Record<string, unknown>)[k], testcase) as { when: string }
  return o.when
}

/** The whole report as Markdown. Pure: the same results always give the same text. */
export function buildReport(results: readonly ScenarioResult[]): string {
  const m: Metrics = computeMetrics(results)
  const c = m.critical, x = c.confusion
  const out: string[] = []
  const p = (...s: string[]) => { for (const x of s) out.push(x, '') }

  p('# Test report: Noa rule benchmark', '_Generated by `npm run benchmark:report` from the same scenario set as the Benchmark tab of the Test case. Fictional, synthetic data only._')

  p('## 1. Summary',
    `- **${m.total} scenarios** were run through Noa's real engine; **${m.passed} match** the outcome that the published rule table asks for (${ci(m.overall)}).`,
    `- **"998 now"** (the decision that matters most), over the ${x.tp + x.fn + x.fp + x.tn} safety scenarios that reach a decision: sensitivity **${ci(c.sensitivity)}**, specificity **${ci(c.specificity)}**. Missed emergencies: **${x.fn}**. False alarms: **${x.fp}**.`,
    `- **${m.failures.length} difference${m.failures.length === 1 ? '' : 's'}** between the rule table and the engine, all listed in section 7. Nothing was changed to make a number look better.`,
    `- This is a check that Noa follows its own published rules, including at the edge of each threshold and on messy input. **It is not clinical validation** (section 9).`)

  p('## 2. What was tested')
  p('The scenarios cover every safety rule R1 to R12, every prevention rule P1 to P9 and the two heart-score rules F1 and F2, each with cases where the rule should fire and cases where it must hold back, plus boundary values, tough input, contradictory answers, night and day, Arabic speech, every barrier and its enabler, and where each result is routed.')
  p(table(['Group', 'Scenarios', 'What it covers'], BENCH_GROUPS.map((g) => [label('group', g), String(SCENARIOS.filter((s) => s.group === g).length), GROUP_NOTE[g]])))

  p('## 3. How it was tested',
    '1. **Synthetic and labelled by hand.** Each scenario is a setup (what the sensors read, what the person says or types, the profile) and an expected outcome written from the published rule table (the sensor rule, the deciding rule, the decision such as "998 now" or "home plan" or "no action", and the agent that takes it). No patient data is used.',
    '2. **The real engine, one fresh run per scenario.** The runner drives a new `TestCaseEngine` for each scenario, with no timers: the playback and the pipeline are drained, exactly as the "Run it for me" autopilot does. The engine\'s sensor noise (about 3 beats a minute) is switched off so that the heart rate typed in is the reading; with the noise on, a value at the edge such as 121 can dip under the threshold.',
    '3. **What "match" means.** The sensor rule (R1 to R4), the speech check level when it is part of the case, the deciding rule, the decision, the agent and, where it applies, the routing or the warning all agree with the expectation. On a difference the run records the first step and the agent where Noa diverged: input check, sensor rule (Noa Guardian), speech check (Noa Voice), decision (Noa).',
    '4. **Intervals.** Every percentage comes with a 95% Wilson score interval (z = 1.96). "Sensitivity" is the share of scenarios the table sends to 998 that Noa sent to 998; "specificity" is the share of the others that Noa kept out of 998.')

  p('## 4. Accuracy by group',
    table(['Group', 'Scenarios', 'Match'], BENCH_GROUPS.map((g) => [label('group', g), String(m.byGroup[g].n), ci(m.byGroup[g])])))

  p('## 5. Accuracy by rule',
    'A rule is tested where it should fire ("fire") and where it must hold back ("hold"). R1 to R4 start a check; R5 to R12 decide.',
    table(['Rule', 'Published when', 'Fire', 'Hold', 'Match'], m.byRule.map((r) => [r.rule, ruleWhen(r.rule), String(r.positives), String(r.negatives), ci(r)])))

  p('## 6. The decision that matters most: 998 now',
    table(['', 'Noa: 998 now', 'Noa: not 998'], [['**Rule table: 998 now**', String(x.tp), `${x.fn} (missed emergencies)`], ['**Rule table: not 998**', `${x.fp} (false alarms)`, String(x.tn)]]),
    table(['Measure', 'Value'], [
      ['Sensitivity', ci(c.sensitivity)], ['Specificity', ci(c.specificity)],
      ['Positive predictive value', ci(c.ppv)], ['Negative predictive value', ci(c.npv)],
    ]),
    '### Subgroups',
    'The same rules should give the same answers however a scenario is tagged. The 998 columns cover the safety scenarios only; a small group has a wide interval, so read the interval before the percentage.',
    table(['Subgroup', 'Scenarios', 'Match', 'Sensitivity, 998', 'Specificity, 998'], SUBGROUPS.flatMap(([dim, keys, title]) => [
      [`**${title}**`, '', '', '', ''],
      ...keys.map((k) => [((en.tag as Record<string, Record<string, string>>)[dim])[k], String((m.subgroups[dim] as Record<string, Rate>)[k].n), ci((m.subgroups[dim] as Record<string, Rate>)[k]), ci(m.criticalBy[dim][k].sensitivity), ci(m.criticalBy[dim][k].specificity)]),
    ])))

  const tough = results.filter((r) => r.scenario.tags.level === 'tough')
  p('## 7. Tough cases and the differences found',
    `**Tough cases** are the scenarios with missing values, values that cannot be real, contradictory answers, typed speech with typos or in the wrong language, and values at the very edge of the plausible range. There are ${tough.length}; ${tough.filter((r) => r.pass).length} match (${ci(m.subgroups.level.tough)}). The input guardrail refuses a missing or implausible sensor or screening value (the previous valid value stays, the run waits for a valid one); family profile and result values are kept inside their range with a warning.`)
  p('**Found by this benchmark and fixed in the engine** (the scenarios now match):', FIXED.map((f) => `- ${f}`).join('\n'))
  if (m.failures.length === 0) p('**No differences.** Every scenario matches the rule table.')
  else {
    p('**Differences between the rule table and the engine** (expected, what Noa did, where it diverged first):')
    p(table(['Scenario', 'Expected', 'Noa did', 'First difference', 'Finding'], m.failures.map((f) => [
      `${f.id}: ${f.scenario.title}`, dec(f.scenario.expected), dec(f.actual),
      f.divergence ? `${label('step', f.divergence.step)}, ${label('agent', f.divergence.agent)}, ${label('field', f.divergence.field)}: expected ${f.divergence.expected}, got ${f.divergence.actual}` : '',
      FINDINGS[f.id] ?? f.scenario.note ?? '',
    ])))
  }
  p(`### Tough cases (${tough.length})`, table(['Scenario', 'Expected', 'Noa did', 'Result'], tough.map((r) => [`${r.id}: ${r.scenario.title}`, dec(r.scenario.expected), dec(r.actual), r.pass ? 'match' : '**differs**'])))

  p('## 8. Reproduce',
    '```',
    'cd web',
    'npm install',
    'npm run benchmark:report     # re-runs the set and rewrites this file',
    'npm run dev                  # then open any page with ?test=bench for the Benchmark tab',
    '```',
    'The set is `web/src/features/testcase/bench/scenarios.ts`; the runner is `runner.ts` and the metric maths `metrics.ts`, in the same folder, with unit tests in `web/tests/benchmark/`.')

  p('## 9. Limits, in plain words',
    '- The scenarios are synthetic and few. A high score on made-up cases says that Noa follows its rules; it says nothing about how often the rules are right for real people.',
    '- The expected outcomes come from the published rule table and the prototype\'s demo thresholds, which are not clinical guidance. The labels were written by the team, not by an independent clinician, so a mistake in the table is copied into the labels.',
    '- The sensor playback is simulated and the sensor noise is off for the boundary cases; real devices will not give clean values.',
    '- The speech check is a demo score (words matched and time taken), not a validated stroke test.',
    '- Noa is decision support, not a diagnosis: the doctor decides.')

  p('## Appendix: every scenario',
    table(['Id', 'Group', 'Tags', 'Scenario', 'Expected', 'Noa did', 'Result'], results.map((r) => [
      r.id, label('group', r.scenario.group),
      `${r.scenario.tags.lang}, ${r.scenario.tags.time}, ${r.scenario.tags.age}, ${r.scenario.tags.level}`,
      r.scenario.title, dec(r.scenario.expected), dec(r.actual), r.pass ? 'match' : '**differs**',
    ])))
  return out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n'
}

const GROUP_NOTE: Record<string, string> = {
  'safety-rules': 'Each safety rule where it should fire and where it must not, in plain cases.',
  boundary: 'Just under, exactly at and just over each threshold: heart rate 120 and 121, 9 and 10 minutes, glucose 4.0 and 3.9, oxygen 90 and 89, speech score 0.6 and 0.8.',
  'tough-input': 'Heart rate 400, an oxygen of 150%, a glucose of 0.2, text, empty or missing values: refused; the value corrected afterwards drives the decision.',
  contradictory: 'Normal speech with "I can\'t get up", a reassuring answer with slurred speech, two rules met in the same minute.',
  'night-day': 'The same cases at six times of day (01:12 to 23:30): the answer must not depend on the clock.',
  arabic: 'The speech check in Arabic: usual, slurred, none, typed with other spellings, typed in the wrong language.',
  people: 'The same rules for a child, adults and older adults (nine people).',
  'prevention-rules': 'Eligible or not (P1, P2) at the age edges, every barrier answered with its enabler (P3 to P8), implausible ages refused.',
  'prevention-results': 'Where a result goes (P9): well-child words, HbA1c, weight centile, bone T-score, each side of its threshold.',
  'family-results': 'The nine results of the family case, each side of its threshold, and values clamped with a warning.',
  'family-forecast': 'The heart score (F1 and F2): the 20% and 10% bands, ages 29 to 30 and 74 to 75, a known heart attack or stroke, a child, and the one-alert rule.',
}

const SUBGROUPS: [('lang' | 'time' | 'age' | 'level'), string[], string][] = [
  ['lang', ['en', 'ar'], 'Language'], ['time', ['day', 'night'], 'Time of day'], ['age', ['child', '18-39', '40-64', '65+'], 'Age band'], ['level', ['easy', 'tough'], 'Difficulty'],
]

/** Run the whole set and write `docs/submission/test-report.md` (from `web/`). Returns the path. */
export function writeReport(file = resolve(process.cwd(), '..', 'docs', 'submission', 'test-report.md')): string {
  const text = buildReport(runAllSync(SCENARIOS))
  mkdirSync(dirname(file), { recursive: true })
  writeFileSync(file, text, 'utf8')
  return file
}
